"""功能说明：AI 路线规划提示词工具。"""


def build_intent_messages(city: str, budget: str, travel_time: str, preferences: str, origin_location: str = '') -> list[dict[str, str]]:
    """功能说明：构造意图识别提示词。"""
    system_prompt = (
        '你是一个旅游路线规划助手。请根据用户输入，识别并结构化用户的旅游意图。\n'
        '请返回 JSON 格式，包含以下字段：\n'
        '- city: 目的地城市\n'
        '- budget: 预算金额（数字）\n'
        '- budget_type: 预算类型（低预算/中等预算/高预算）\n'
        '- travel_days: 旅行天数（数字）\n'
        '- preferences: 旅行偏好关键词列表\n'
        '- pace: 行程节奏偏好（轻松/均衡/紧凑）\n'
        '- origin_location: 用户出发地（如有）\n'
        '只返回 JSON，不要附加其他文字。'
    )
    origin_line = f'出发地点：{origin_location}\n' if origin_location else ''
    user_prompt = (
        f'目的地城市：{city}\n'
        f'{origin_line}'
        f'预算：{budget}\n'
        f'出行时间：{travel_time}\n'
        f'旅行偏好：{preferences}'
    )
    return [
        {'role': 'system', 'content': system_prompt},
        {'role': 'user', 'content': user_prompt},
    ]


